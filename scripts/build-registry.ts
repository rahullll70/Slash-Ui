// @ts-nocheck
import { writeFileSync, existsSync, mkdirSync, readFileSync } from 'fs';
import path from 'path';
import { Index } from '../registry/index';

const OUTPUT_DIR = path.join(process.cwd(), '__registry__');
const OUTPUT_PATH = path.join(OUTPUT_DIR, 'index.ts');
const COMPONENTS_PATH = path.join(OUTPUT_DIR, 'components.ts');
const SEARCH_INDEX_PATH = path.join(OUTPUT_DIR, 'search-index.ts');

async function buildRegistry() {
  if (!existsSync(OUTPUT_DIR)) {
    mkdirSync(OUTPUT_DIR);
  }

  const escape = (str: string) =>
    (str || '').replace(/`/g, '\\`').replace(/\$/g, '\\$');

  let indexContent = `// @ts-nocheck
// This file is autogenerated by scripts/build-registry.ts
import * as React from "react"

export const Index: Record<string, any> = {
  "default": {
`;

  Index.forEach((item: any) => {
    const componentPath = item.files[0].replace(/\.tsx?$/, '');
    const sourceFilePath = path.join(process.cwd(), 'registry', item.files[0]);
    const rawContent = existsSync(sourceFilePath)
      ? readFileSync(sourceFilePath, 'utf8')
      : '';

    indexContent += `    "${item.name}": {
      name: "${item.name}",
      type: "${item.type}",
      component: React.lazy(() => import("@/registry/${componentPath}")),
      files: ${JSON.stringify(item.files)},
      category: "${item.category || 'undefined'}",
      content: \`${escape(rawContent)}\`,
      description: \`${escape(item.description)}\`,
      install: "${item.install || ''}",
      dependencies: ${JSON.stringify(item.dependencies || [])},
      interactionType: ${JSON.stringify(item.interactionType || [])},
      howToUse: \`${escape(item.howToUse)}\`,
    },
`;
  });

  indexContent += `  }
};`;

  writeFileSync(OUTPUT_PATH, indexContent);

  // ── Generate components.ts (Lazy Imports only) ──
  let componentsContent = `// @ts-nocheck
// This file is autogenerated by scripts/build-registry.ts
import * as React from "react"

export const Components: Record<string, React.LazyExoticComponent<any>> = {
`;

  Index.forEach((item: any) => {
    const componentPath = item.files[0].replace(/\.tsx?$/, '');
    componentsContent += `  "${item.name}": React.lazy(() => import("@/registry/${componentPath}")),\n`;
  });

  componentsContent += `};`;

  writeFileSync(COMPONENTS_PATH, componentsContent);

  // ── Generate search-index.ts (slim metadata only, safe to import everywhere) ──
  // No `content`, `howToUse`, `description`, or `component` fields here —
  // this file must stay tiny since it's imported from app-wide layout/search UI.
  const searchEntries = Index.map((item: any) => ({
    name: item.name,
    category: item.category || 'undefined',
    path: `/component/${item.name}`,
  }));

  const searchIndexContent = `// @ts-nocheck
// This file is autogenerated by scripts/build-registry.ts
// Slim metadata only — safe to import from layout/search UI on every page.
// Do NOT add component/content/description fields here; use __registry__/index.ts for that.

export const SearchIndex = ${JSON.stringify(searchEntries, null, 2)} as const;
`;

  writeFileSync(SEARCH_INDEX_PATH, searchIndexContent);

  console.log('✅ Slash UI Registry updated (index.ts, components.ts, search-index.ts)');
}

buildRegistry();